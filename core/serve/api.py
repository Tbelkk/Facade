"""REST API generated from operations.json (FastAPI), with the MCP endpoint mounted at /mcp.

Read endpoints answer from the records with operator_agent/query.py (the same rules the Operator used to
make its examples). Write endpoints (source "legacy") answer 501 until the Writer is connected.
/docs shows the generated OpenAPI spec.
"""
from fastapi import FastAPI, Request
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import JSONResponse, Response

from operator_agent import query

from .mcp import JSON_TYPE, MCPServer


def openapi_spec(state):
    paths = {}
    for op in state["ops"]["operations"]:
        params = [{"name": i["name"], "in": "path" if i.get("in") == "path" else "query", "required": i.get("in") == "path" or bool(i.get("required")),
                   "schema": {"type": JSON_TYPE.get(i.get("type"), "string"), **({"enum": i["values"]} if i.get("values") else {})}}
                  for i in op.get("inputs", []) if i.get("in") in ("path", "query")]
        entry = {"operationId": op["name"], "summary": op.get("summary", ""), "tags": [op.get("entity", "data")], "parameters": params,
                 "responses": {"200": {"description": "OK"}}}
        if op.get("method") != "GET":
            entry["requestBody"] = {"content": {"application/json": {"schema": {"type": "object", "properties": {
                i["name"]: {"type": JSON_TYPE.get(i.get("type"), "string")} for i in op.get("inputs", []) if i.get("in") == "body"}}}}}
            entry["responses"] = {"501": {"description": "Write endpoints run through the Writer (not connected yet)"}}
        paths.setdefault(op["path"], {})[op["method"].lower()] = entry
    return {"openapi": "3.0.3", "info": {"title": f"Facade API for {state.get('site')}", "version": "1.0",
                                          "description": f"Generated by Facade from {state.get('site')}. Data source: {state.get('source')}."},
            "paths": paths}


def build_app(state):
    app = FastAPI(title=f"Facade API · {state.get('site')}", docs_url="/docs", openapi_url="/openapi.json")
    app.openapi = lambda: openapi_spec(state)   # the spec comes from operations.json, not from Python signatures
    app.add_middleware(CORSMiddleware, allow_origins=["*"], allow_methods=["*"], allow_headers=["*"])
    mcp = MCPServer(state, name=f"facade-{(state.get('site') or 'site').split('//')[-1].split('/')[0]}")
    app.state.facade, app.state.mcp = state, mcp

    @app.get("/", include_in_schema=False)
    def _index():
        ops = state["ops"]["operations"]
        return {"site": state.get("site"), "source": state.get("source"), "docs": "/docs", "mcp": "/mcp",
                "records": {k: len(v) for k, v in state["records"].items()},
                "endpoints": [f"{o['method']} {o['path']}" for o in ops], "mcp_tools": [t["name"] for t in mcp.tools()]}

    def make_handler(op):
        async def handler(request: Request):
            if op.get("source") != "database" or op.get("method") != "GET":
                return JSONResponse({"status": "not_available", "error": "Write endpoints run through the Writer agent, which isn't connected yet."}, status_code=501)
            params = {**dict(request.query_params), **dict(request.path_params)}
            result = query.run(op, params, state["records"])
            if isinstance(result, dict) and result.get("error") == "not found":
                return JSONResponse(result, status_code=404)
            return JSONResponse(result)
        handler.__name__ = op["name"]
        return handler

    # fixed paths before {param} paths, so /posts/search isn't swallowed by /posts/{id}
    for op in sorted(state["ops"]["operations"], key=lambda o: ("{" in o["path"], o["path"])):
        app.add_api_route(op["path"], make_handler(op), methods=[op["method"]], name=op["name"], include_in_schema=False)

    # MCP over Streamable HTTP: one JSON-RPC message (or a batch) per POST, answered with JSON
    @app.post("/mcp", include_in_schema=False)
    async def _mcp(request: Request):
        try:
            body = await request.json()
        except Exception:
            return JSONResponse({"jsonrpc": "2.0", "id": None, "error": {"code": -32700, "message": "Parse error"}}, status_code=400)
        if isinstance(body, list):
            out = [r for r in (mcp.handle(m) for m in body) if r is not None]
            return JSONResponse(out) if out else Response(status_code=202)
        res = mcp.handle(body)
        return JSONResponse(res) if res is not None else Response(status_code=202)

    @app.get("/mcp", include_in_schema=False)
    def _mcp_get():
        return Response(status_code=405)

    return app
